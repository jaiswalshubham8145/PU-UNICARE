import { useQuery, useMutation, useQueryClient } from "@tanstack/react-query";
import { supabase } from "@/integrations/supabase/client";
import { useAuth } from "./useAuth";
import { Database } from "@/integrations/supabase/types";
import { TABLES } from "@/config/constants";
import { sendComplaintEmail, ComplaintEmailData } from "@/services/emailService";
import autoAssignmentEngine from "@/services/AutoAssignmentEngine";

type ComplaintPriority = Database['public']['Enums']['complaint_priority'];
type ComplaintStatus = Database['public']['Enums']['complaint_status'];

interface ComplaintInsert {
  title: string;
  description: string;
  location: string;
  department_id: string;
  category_id: string;
  priority: ComplaintPriority;
  image_urls?: string[];
  building_id?: string;
}

export const useComplaints = () => {
  const { user, roles } = useAuth();
  const queryClient = useQueryClient();

  // Fetch user's own complaints
  const { data: myComplaints, isLoading: loadingMyComplaints } = useQuery({
    queryKey: ["my-complaints", user?.id],
    queryFn: async () => {
      if (!user) return [];
      const { data, error } = await supabase
        .from(TABLES.COMPLAINTS)
        .select(`
          *,
          departments(name),
          maintenance_categories(name),
          buildings(name)
        `)
        .eq("submitted_by", user.id)
        .order("created_at", { ascending: false });

      if (error) throw error;
      return data;
    },
    enabled: !!user,
  });

  // Fetch department complaints (for HOD)
  const { data: departmentComplaints, isLoading: loadingDeptComplaints, error: deptError } = useQuery({
    queryKey: ["department-complaints", user?.id],
    queryFn: async () => {
      if (!user) return [];
      const { data, error } = await supabase
        .from(TABLES.COMPLAINTS)
        .select(`
          *,
          departments(name),
          maintenance_categories(name),
          buildings(name)
        `)
        .order("created_at", { ascending: false });

      if (error) throw error;
      return data;
    },
    enabled: !!user && roles.includes("hod"),
  });

  // Fetch all complaints (for admin)
  const { data: allComplaints, isLoading: loadingAllComplaints } = useQuery({
    queryKey: ["all-complaints"],
    queryFn: async () => {
      const { data, error } = await supabase
        .from(TABLES.COMPLAINTS)
        .select(`
          *,
          departments(name),
          maintenance_categories(name),
          buildings(name)
        `)
        .order("created_at", { ascending: false });

      if (error) throw error;
      return data;
    },
    enabled: !!user && (roles.includes("admin") || roles.includes("principal")),
  });

  // Submit new complaint
  const submitComplaint = useMutation({
    mutationFn: async (complaint: ComplaintInsert) => {
      if (!user) throw new Error("Not authenticated");

      // Use type assertion since complaint_number is auto-generated by trigger
      const insertData = {
        title: complaint.title,
        description: complaint.description,
        location: complaint.location,
        department_id: complaint.department_id,
        category_id: complaint.category_id,
        priority: complaint.priority,
        image_urls: complaint.image_urls || null,
        building_id: complaint.building_id || null,
        submitted_by: user.id,
      } as Partial<Database['public']['Tables']['complaints']['Insert']> as Database['public']['Tables']['complaints']['Insert'];

      const { data, error } = await supabase
        .from(TABLES.COMPLAINTS)
        .insert(insertData)
        .select()
        .single();

      if (error) throw error;

      // Trigger email notification to all relevant parties
      try {
        // Fetch category and department names for the email
        const { data: category } = await supabase
          .from(TABLES.MAINTENANCE_CATEGORIES)
          .select("name")
          .eq("id", complaint.category_id)
          .single();

        const { data: department } = await supabase
          .from(TABLES.DEPARTMENTS)
          .select("name")
          .eq("id", complaint.department_id)
          .single();

        // Use centralized email service
        const emailData: ComplaintEmailData = {
          id: data.id,
          complaint_number: data.complaint_number,
          title: data.title,
          description: data.description,
          priority: data.priority,
          status: data.status,
          location: data.location,
          department_id: data.department_id,
          submitted_by: data.submitted_by,
          category_name: category?.name || "Maintenance",
          department_name: department?.name,
        };

        sendComplaintEmail("new_complaint", emailData).catch(console.error);
      } catch (emailError) {
        console.error("Failed to trigger email:", emailError);
        // Don't fail the submission if email fails
      }

      // Auto-assign the complaint to the best available maintenance staff
      try {
        const assignmentResult = await autoAssignmentEngine.autoAssign(
          data.id,
          complaint.category_id,
          complaint.department_id,
          complaint.priority
        );

        if (assignmentResult) {
          console.log(
            `Auto-assigned complaint ${data.complaint_number} to staff`,
            assignmentResult.assigned_to_user_id,
            `(Score: ${assignmentResult.total_score}, Reason: ${assignmentResult.assignment_reason})`
          );

          // Send assignment email notification
          try {
            const emailData: ComplaintEmailData = {
              id: data.id,
              complaint_number: data.complaint_number,
              title: data.title,
              description: data.description,
              priority: data.priority,
              status: 'approved',
              location: data.location,
              department_id: data.department_id,
              submitted_by: data.submitted_by,
              assigned_to: assignmentResult.assigned_to_user_id,
              category_name: category?.name || 'Maintenance',
              department_name: department?.name,
            };
            sendComplaintEmail("assignment", emailData, {
              note: `Auto-assigned: ${assignmentResult.assignment_reason}`,
            }).catch(console.error);
          } catch (assignEmailError) {
            console.error("Failed to send assignment email:", assignEmailError);
          }
        } else {
          console.log(
            `No available staff for auto-assignment of complaint ${data.complaint_number}. Complaint remains pending for HOD manual assignment.`
          );
        }
      } catch (autoAssignError) {
        console.error("Auto-assignment failed (complaint still submitted):", autoAssignError);
        // Don't fail the submission if auto-assignment fails
        // The complaint stays as 'pending' and HOD can manually assign
      }

      return data;
    },
    onSuccess: () => {
      queryClient.invalidateQueries({ queryKey: ["my-complaints"] });
      queryClient.invalidateQueries({ queryKey: ["department-complaints"] });
      queryClient.invalidateQueries({ queryKey: ["all-complaints"] });
      queryClient.invalidateQueries({ queryKey: ["complaint-stats"] });
    },
  });

  // Update complaint status (for HOD/Admin)
  const updateComplaintStatus = useMutation({
    mutationFn: async ({
      complaintId,
      status,
      note
    }: {
      complaintId: string;
      status: ComplaintStatus;
      note?: string;
    }) => {
      if (!user) throw new Error("Not authenticated");

      // Update complaint status
      const { error: updateError } = await supabase
        .from(TABLES.COMPLAINTS)
        .update({ status })
        .eq("id", complaintId);

      if (updateError) throw updateError;

      // Add update record
      const { error: insertError } = await supabase
        .from(TABLES.COMPLAINT_UPDATES)
        .insert({
          complaint_id: complaintId,
          status,
          updated_by: user.id,
          note: note || `Status changed to ${status}`,
        });

      if (insertError) throw insertError;
    },
    onSuccess: () => {
      queryClient.invalidateQueries({ queryKey: ["my-complaints"] });
      queryClient.invalidateQueries({ queryKey: ["department-complaints"] });
      queryClient.invalidateQueries({ queryKey: ["all-complaints"] });
    },
  });

  return {
    myComplaints,
    departmentComplaints,
    allComplaints,
    loadingMyComplaints,
    loadingDeptComplaints,
    loadingAllComplaints,
    submitComplaint,
    updateComplaintStatus,
    errorDeptComplaints: deptError,
  };
};

export const useDepartments = () => {
  return useQuery({
    queryKey: ["departments"],
    queryFn: async () => {
      const { data, error } = await supabase
        .from(TABLES.DEPARTMENTS)
        .select("*")
        .order("name");

      if (error) throw error;
      return data;
    },
  });
};

